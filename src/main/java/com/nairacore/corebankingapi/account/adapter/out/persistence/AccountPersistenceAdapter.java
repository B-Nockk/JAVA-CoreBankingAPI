package com.nairacore.corebankingapi.account.adapter.out.persistence;

import com.nairacore.corebankingapi.account.application.port.out.AccountPersistencePort;
import com.nairacore.corebankingapi.account.domain.Account;
import org.springframework.stereotype.Repository;

import java.util.Optional;

@Repository // Tells Spring to manage this class
public class AccountPersistenceAdapter implements AccountPersistencePort {

    private final AccountRepository repository;

    // Constructor injection (Spring automatically passes the repository in)
    public AccountPersistenceAdapter(AccountRepository repository) {
        this.repository = repository;
    }

    @Override
    public void save(Account account) {
        // Map Domain -> Entity
        AccountJpaEntity entity = new AccountJpaEntity(
                null, // ID is auto-generated by the DB
                account.getAccountNumber(),
                account.getBalance(),
                account.getStatus().name() // Convert Enum to String
        );
        repository.save(entity);
    }

    @Override
    public Optional<Account> loadAccount(String accountNumber) {
        // Fetch from DB, then Map Entity -> Domain
        return repository.findByAccountNumber(accountNumber)
                .map(entity -> {
                    Account account = new Account(entity.getAccountNumber(), entity.getBalance());
                    // In a real app, you'd also map the status back here
                    return account;
                });
    }
}